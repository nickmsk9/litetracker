function rules_h($value)
{
	return htmlspecialchars((string) $value, ENT_QUOTES, 'UTF-8');
}

function rules_yes_no($value)
{
	return !empty($value) ? 'включено' : 'выключено';
}

function rules_class_permissions_text($classMeta)
{
	$permissions = array(
		'details_view' => 'просмотр релизов',
		'download_torrent' => 'скачивание torrent-файлов',
		'download_magnet' => 'magnet-ссылки',
		'upload' => 'загрузка релизов',
		'edit_release' => 'редактирование релизов',
		'comments_edit' => 'редактирование комментариев',
		'comments_delete' => 'удаление комментариев',
		'setting_user' => 'редактирование пользователей',
		'users_view' => 'список пользователей',
		'sessions_view' => 'сессии',
		'search_query' => 'мониторинг поиска',
		'cats' => 'категории',
		'EDIT_PRIV' => 'классы и права',
	);

	$enabled = array();
	foreach ($permissions as $key => $label) {
		if (!empty($classMeta[$key])) {
			$enabled[] = $label;
		}
	}

	return $enabled ? implode(', ', $enabled) : 'специальные права не включены';
}

